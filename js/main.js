/* Casa Nungwi – menu, language-choice memory, lightbox, inquiry form. No dependencies.
   All text and photos are already in the HTML (generated by scripts/build.js). */
(() => {
  'use strict';
  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => Array.from(r.querySelectorAll(s));
  const store = {
    get(k) { try { return localStorage.getItem(k); } catch (e) { return null; } },
    set(k, v) { try { localStorage.setItem(k, v); } catch (e) { /* ignore */ } }
  };

  /* mobile menu */
  const menuBtn = $('#menu-btn'), nav = $('#nav');
  if (menuBtn && nav) menuBtn.addEventListener('click', () => {
    menuBtn.setAttribute('aria-expanded', String(nav.classList.toggle('open')));
  });

  /* language switcher: links go to the same page in the other language; remember the choice */
  const langBox = $('#lang');
  if (langBox) {
    $$('a[data-lang]', langBox).forEach(a => a.addEventListener('click', () => store.set('lang', a.dataset.lang)));
    document.addEventListener('click', e => { if (!langBox.contains(e.target)) langBox.open = false; });
    document.addEventListener('keydown', e => { if (e.key === 'Escape' && langBox.open) { langBox.open = false; $('summary', langBox).focus(); } });

    // Returning visitor who chose another language lands on an English page from outside the site -> take them to their language.
    const saved = store.get('lang');
    let external = true;
    try { external = !document.referrer || new URL(document.referrer).origin !== location.origin; } catch (e) { /* keep true */ }
    if (document.documentElement.lang === 'en' && saved && saved !== 'en' && external) {
      const target = $(`a[data-lang="${saved}"]`, langBox);
      if (target) location.replace(target.getAttribute('href') + location.search);
    }
  }

  /* gallery lightbox */
  const gal = $('#gallery'), dlg = $('#lightbox');
  if (gal && dlg && dlg.showModal) {
    const img = $('img', dlg);
    gal.addEventListener('click', e => {
      const b = e.target.closest('button[data-src]'); if (!b) return;
      img.src = b.dataset.src; img.alt = b.getAttribute('aria-label') || '';
      dlg.showModal();
    });
    dlg.addEventListener('click', e => { if (e.target === dlg) dlg.close(); });
    $('#lightbox-close', dlg).addEventListener('click', () => dlg.close());
  }

  /* inquiry form */
  const form = $('#inquiry');
  if (form) {
    const status = $('#form-status'), submit = $('button[type="submit"]', form);
    const arrival = $('#arrival'), departure = $('#departure'), apt = $('#apartment');
    const m = (k) => form.dataset['msg' + k];
    const today = new Date().toISOString().slice(0, 10);
    arrival.min = today; departure.min = today;
    arrival.addEventListener('change', () => { departure.min = arrival.value || today; });
    const wanted = new URLSearchParams(location.search).get('apt');
    if (wanted && $(`option[value="${CSS.escape(wanted)}"]`, apt)) apt.value = wanted;
    const show = (msg, ok) => { status.textContent = msg; status.className = 'status show ' + (ok ? 'ok' : 'err'); };
    form.addEventListener('submit', async e => {
      e.preventDefault();
      if (form.elements._gotcha && form.elements._gotcha.value) return; // honeypot: only bots fill it
      if (arrival.value && departure.value && departure.value <= arrival.value) { show(m('Dates'), false); departure.focus(); return; }
      if (/TODO/.test(form.action)) { show(m('Todo'), false); return; }
      submit.disabled = true; const label = submit.textContent; submit.textContent = m('Sending');
      try {
        const r = await fetch(form.action, { method: 'POST', body: new FormData(form), headers: { Accept: 'application/json' } });
        if (!r.ok) throw new Error(r.status);
        form.reset(); show(m('Success'), true);
      } catch (err) { show(m('Error'), false); }
      finally { submit.disabled = false; submit.textContent = label; }
    });
  }
})();
